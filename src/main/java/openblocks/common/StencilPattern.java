	public static final StringRepresentable.EnumCodec<StencilPattern> CODEC = StringRepresentable.fromEnum(StencilPattern::values);

	public static final int SIZE = 16;

	private final BitSet bits = new BitSet(SIZE * SIZE);

	StencilPattern(String... rows) {
		Preconditions.checkState(rows.length == SIZE, "Invalid row count");
		for (int y = 0; y < SIZE; y++) {
			Preconditions.checkState(rows[y].length() == SIZE, "Invalid row length");
			for (int x = 0; x < SIZE; x++)
				if (rows[y].charAt(x) != ' ') bits.set(y * SIZE + x);
		}
	}

	public boolean isCutOut(int x, int y) {
		return bits.get(y * SIZE + x);
	}

	@Override
	public String getSerializedName() {
		return name().toLowerCase(Locale.ROOT);
	}
